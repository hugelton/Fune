"""Bakes the 8 x 8 pixel font of the game-screen pages (LOFI) from assets/fonts/PressStart2P-Regular.ttf (SIL OFL 1.1) into
src/ui/pixfont8.c: printable ASCII (32 .. 126), eight rows a glyph, bit 7 the leftmost pixel. The font is drawn on an 8 px grid,
so at 8 px it rasterises exactly (no pixel outside its cell: checked). The baked data stays under the OFL (its file says so);
it is not named after the font (the OFL's Reserved Font Name). Needs Pillow:  python3 tools/gen_pix8.py"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = ROOT / "assets" / "fonts" / "PressStart2P-Regular.ttf"


def glyph(font, ch):
    im = Image.new("1", (16, 16), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((4, 4), ch, font=font, fill=1)
    for y in range(16):
        for x in range(16):
            assert not (im.getpixel((x, y)) and not (4 <= x < 12 and 4 <= y < 12)), "glyph %r spills out of 8 x 8" % ch
    return [sum((1 << (7 - x)) for x in range(8) if im.getpixel((4 + x, 4 + y))) for y in range(8)]


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "src" / "ui" / "pixfont8.c"
    font = ImageFont.truetype(str(TTF), 8)
    lines = ["/* SPDX-License-Identifier: OFL-1.1",
             " * Copyright 2012 The Press Start 2P Project Authors (cody@zone38.net), with Reserved Font Name \"Press Start 2P\".",
             " * Licensed under the SIL Open Font License, Version 1.1: assets/fonts/OFL-PressStart2P.txt */",
             "/* generated by tools/gen_pix8.py from assets/fonts/PressStart2P-Regular.ttf: the 8 x 8 pixel font of the game-screen pages,",
             " * printable ASCII from ' ', eight rows a glyph, bit 7 the leftmost pixel. Do not edit. */",
             "#include <stdint.h>", "const uint8_t K_PIX8[95][8] = {"]
    for c in range(32, 127):
        ch = chr(c)
        g = glyph(font, ch)
        lines.append("    {%s},   /* %s */" % (", ".join("0x%02X" % b for b in g), ch if ch not in "*/\\" else "0x%02X" % c))
    lines.append("};")
    out.write_text("\n".join(lines) + "\n")
    print("95 glyphs ->", out)


if __name__ == "__main__":
    main()
