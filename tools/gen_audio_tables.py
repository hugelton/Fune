"""src/fe_tables.h: the tables the Felucca engines need (SINE, PITCH_OCT, SVF_G, TANH_Q15, from
tools/gen_engine_tables.py) at FS = 44100, CTL = 32, and Kreisel's envelope tables
(ENV_LIN, ENV_EXP, LFO_INC: the same curves as Felucca 2.0's tools/gen_tables.py, the author's own, relicensed MPL-2.0, with the author's
permission). Everything is const: the FM-1 keeps it in flash.   usage: gen_audio_tables.py src/fe_tables.h"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_engine_tables as fe  # noqa: E402

FS, CTL = fe.FS, fe.CTL


def main(path):
    L = ["/* generated by tools/gen_audio_tables.py. Do not edit. */", "#pragma once", "#include <stdint.h>",
         f"#define FS {FS}", f"#define CTL {CTL}", ""]
    L += fe.sine() + fe.pitch() + fe.svf_g() + fe.tanh_q15()
    ms = [1.0 * (10000 ** (v / 127)) for v in range(128)]            # times 1 ms .. 10 s, exponential
    L += fe.arr("ENV_LIN", "uint32_t", [max(1, int((1 << 24) * CTL / (m * FS / 1000))) for m in ms], 8)   # attack: Q24 a block
    exp_k = []
    for m in ms:                                                     # decay / release: ~99 % of the way after m ms, Q16 a block
        tau = m / 1000 / 4.6
        exp_k.append(max(1, min(65535, int(65536 * (1 - math.exp(-CTL / (tau * FS)))))))
    L += fe.arr("ENV_EXP", "uint16_t", exp_k)
    # the LFO's phase step a block: 0.05 .. 40 Hz, exponential (the LFO page's RATE: ui/draw.c KF_LFOHZ); the form of Felucca 2.0's
    # LFO_INC (the author's own, relicensed MPL-2.0)
    L += fe.arr("LFO_INC", "uint32_t", [int(0.05 * 800 ** (v / 127) * CTL / FS * 2 ** 32) for v in range(128)], 8)
    Path(path).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
