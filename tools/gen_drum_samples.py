"""DRUM's sample pieces: assets/drums/*.wav (the owner's, from Virtuosity Drums, CC0) into src/drum_samples.c.

Each file: to mono (the channels averaged), to 44.1 kHz (a windowed-sinc low-pass, then linear steps: the FM-1's rate), its
silence cut at both ends (below -60 dB of its peak; a 5 ms fade at the end), int16. The order is SAMPLES below: the pieces
SP BD, SP CH, SP OH (tools/gen_engines.py DRUM_PIECES, src/drum_kreisel.c DP[]).

    python3 tools/gen_drum_samples.py
"""
import math
import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SAMPLES = [("kick.wav", "SMP_KICK"), ("closed.wav", "SMP_CH"), ("open.wav", "SMP_OH")]
FS = 44100


def read(path):
    w = wave.open(str(path))
    ch, sw, fs, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
    raw = w.readframes(n)
    if sw != 2:
        raise SystemExit("%s: 16-bit WAV only" % path)
    v = struct.unpack("<%dh" % (n * ch), raw)
    return [sum(v[i * ch:(i + 1) * ch]) / ch for i in range(n)], fs


def resample(x, fs):
    if fs == FS:
        return x
    ratio = FS / fs
    cut = min(1.0, ratio) * 0.95            # the low-pass, relative to the source's Nyquist
    taps = 31
    h = []
    for k in range(taps):
        m = k - taps // 2
        s = cut if m == 0 else math.sin(math.pi * cut * m) / (math.pi * m)
        h.append(s * (0.54 - 0.46 * math.cos(2 * math.pi * k / (taps - 1))))
    g = sum(h)
    h = [c / g for c in h]
    y = [sum(h[k] * x[i + k - taps // 2] for k in range(taps) if 0 <= i + k - taps // 2 < len(x)) for i in range(len(x))]
    out, n = [], int(len(y) * ratio)
    for j in range(n):
        p = j / ratio
        i = int(p)
        f = p - i
        a = y[i]
        b = y[i + 1] if i + 1 < len(y) else 0.0
        out.append(a + (b - a) * f)
    return out


def trim(x):
    peak = max(abs(s) for s in x) or 1.0
    th = peak * 10 ** (-60 / 20)
    a = next(i for i, s in enumerate(x) if abs(s) > th)
    b = len(x) - next(i for i, s in enumerate(reversed(x)) if abs(s) > th)
    y = x[a:b]
    fade = int(FS * 0.005)
    for i in range(min(fade, len(y))):
        y[len(y) - 1 - i] *= i / fade
    return y


def main():
    lines = ["/* generated by tools/gen_drum_samples.py from assets/drums (the owner's, after Virtuosity Drums, CC0): DRUM's sample",
             " * pieces, mono int16 at 44.1 kHz. Do not edit. */",
             '#include "drum_samples.h"', ""]
    table, total = [], 0
    for fname, sym in SAMPLES:
        x, fs = read(ROOT / "assets" / "drums" / fname)
        y = trim(resample(x, fs))
        q = [max(-32767, min(32767, int(round(s)))) for s in y]
        total += len(q) * 2
        lines.append("static const int16_t %s[%d] = {" % (sym, len(q)))
        for i in range(0, len(q), 16):
            lines.append("    " + ", ".join(str(s) for s in q[i:i + 16]) + ",")
        lines.append("};")
        table.append("    {%s, %d}," % (sym, len(q)))
        print("%s: %d samples, %.3f s, %d bytes" % (fname, len(q), len(q) / FS, len(q) * 2))
    lines += ["", "const KDrumSample K_DRUM_SAMPLE[K_DRUM_SAMPLES] = {"] + table + ["};", ""]
    (ROOT / "src" / "drum_samples.c").write_text("\n".join(lines))
    print("total %d bytes -> src/drum_samples.c" % total)


if __name__ == "__main__":
    main()
