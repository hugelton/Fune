/* ------------------------------------------------------------ canvas --- */
int g_init(GCanvas *c, int w, int h) { return g_init_scaled(c, w, h, 1); }
int g_init_scaled(GCanvas *c, int w, int h, int s)
{
    if (s < 1) s = 1;
    c->w = w; c->h = h; c->s = s; c->pw = w * s; c->ph = h * s;
    c->px = calloc((size_t)c->pw * (size_t)c->ph, sizeof *c->px);
    return c->px != NULL;
}
/* a canvas of s > 1: each call below scales what it is given and draws on the canvas's own pixels (PHYS: those, a unit each) */
#define SC(c) ((c) && (c)->s > 1)
#define PHYS(c) ((GCanvas){(c)->pw, (c)->ph, (c)->px, 1, (c)->pw, (c)->ph})
void g_free(GCanvas *c) { free(c->px); c->px = NULL; }
void g_clear(GCanvas *c, uint32_t col)
{ REC("clear", I_(0, 0, c->w, c->h), I_(col), 0); 
    int i, n = SC(c) ? c->pw * c->ph : c->w * c->h;
    for (i = 0; i < n; i++) c->px[i] = GPIX(col);
}
/* v / 255 rounded, for 0 <= v <= 255 * 255, with a shift and an add (the FM-1 has no divide instruction: a division is a library call) */
static inline int div255(int v) { v += 128; return (v + (v >> 8)) >> 8; }
static inline int blend_ch(int p, int q, int a) { return p + (q > p ? div255((q - p) * a) : -div255((p - q) * a)); }   /* p -> q by a / 255 */
static void put(GCanvas *c, int x, int y, uint32_t col, int a, int max)   /* a / max of col over what is there */
{
    uint32_t d;
    int sh, out = 0;
    if ((unsigned)x >= (unsigned)c->w || (unsigned)y >= (unsigned)c->h || a <= 0) return;
    if (a > max) a = max;
    if (max != 255) a = max == 1 ? 255 : a * 255 / max;
    d = GPIX_RGB(c->px[y * c->w + x]);
    if (a >= 255) { c->px[y * c->w + x] = GPIX(col); return; }
    for (sh = 16; sh >= 0; sh -= 8)
        out |= blend_ch((int)((d >> sh) & 255u), (int)((col >> sh) & 255u), a) << sh;
    c->px[y * c->w + x] = GPIX((uint32_t)out);
}
static inline void fill32(gpix_t *p, int n, gpix_t v)   /* n pixels of one colour: eight a step (a plain loop was the panels' cost) */
{
    while (n >= 8) { p[0] = v; p[1] = v; p[2] = v; p[3] = v; p[4] = v; p[5] = v; p[6] = v; p[7] = v; p += 8; n -= 8; }
    while (n-- > 0) *p++ = v;
}
void g_fill(GCanvas *c, int x, int y, int w, int h, uint32_t col)
{ REC("rect", I_(x, y, w, h, 0, 255), I_(col), 0); 
    if (SC(c)) { GCanvas p = PHYS(c); const int k = c->s; g_fill(&p, x * k, y * k, w * k, h * k, col); return; }
    int i, j, x1 = x + w, y1 = y + h;
    if (x < 0) x = 0;
    if (y < 0) y = 0;
    if (x1 > c->w) x1 = c->w;
    if (y1 > c->h) y1 = c->h;
    (void)i;
    for (j = y; j < y1; j++) fill32(c->px + j * c->w + x, x1 - x, GPIX(col));
}
static uint32_t lerp256(uint32_t a, uint32_t b, int n)   /* a + (b - a) * n / 256 per channel (n 0..256), shifts only */
{
    uint32_t out = 0;
    int sh;
    for (sh = 16; sh >= 0; sh -= 8) {
        int x = (int)((a >> sh) & 255u), y = (int)((b >> sh) & 255u);
        out |= (uint32_t)(x + (((y - x) * n) >> 8)) << sh;
    }
    return out;
}
/* the integer square root of v, by bits (no divide, no float) */
static uint32_t isqrt(uint32_t v)
{
    uint32_t res = 0, bit = 1u << 30;
    while (bit > v) bit >>= 2;
    while (bit) {
        if (v >= res + bit) { v -= res + bit; res = (res >> 1) + bit; }
        else res >>= 1;
        bit >>= 2;
    }
    return res;
}
/* a rounded rectangle: the straight parts are filled directly (or blended by one alpha); only the pixels of the four r x r corners
 * get a coverage, from the distance to the corner's centre, in 1/16 px, in integers (a float operation costs the FM-1 a library call) */
static int use_grad = 0;   /* 0: every gradient is drawn flat, in its middle colour (g_gradients) */
void g_gradients(int on) { use_grad = on; }
/* a corner's coverage (0 .. 16) at quadrant pixel (iq, jq), counted from the corner: r - d + .5 from the corner's centre */
static int rr_cov_at(int r, int iq, int jq)
{
    int dx = (2 * iq + 1 - 2 * r) * 8, dy = (2 * jq + 1 - 2 * r) * 8;   /* 1/16 px */
    int cov = 16 * r - (int)isqrt((uint32_t)(dx * dx + dy * dy)) + 8;
    return cov < 0 ? 0 : cov > 16 ? 16 : cov;
}
#define RR_KEEP 16   /* radii up to this keep their quadrant's table (1 + 4 + .. + 256 = 1496 bytes); a larger one is made when drawn */
#define RR_TAB 32
static uint8_t rr_keep[1496];
static uint16_t rr_keep_at[RR_KEEP + 1];
static uint8_t rr_keep_made[RR_KEEP + 1];
static uint8_t rr_big[RR_TAB * RR_TAB];
static int rr_big_r = -1;
static const uint8_t *rr_table(int r)   /* r x r coverages, row jq at jq * r; 0 when r is past RR_TAB */
{
    uint8_t *t;
    int iq, jq;
    if (r > RR_TAB) return 0;
    if (r <= RR_KEEP) {
        if (rr_keep_made[r]) return rr_keep + rr_keep_at[r];
        if (!rr_keep_at[RR_KEEP]) { int k, at = 0; for (k = 1; k <= RR_KEEP; k++) { rr_keep_at[k] = (uint16_t)at; at += k * k; } }
        t = rr_keep + rr_keep_at[r];
        rr_keep_made[r] = 1;
    } else {
        if (r == rr_big_r) return rr_big;
        t = rr_big;
        rr_big_r = r;
    }
    for (jq = 0; jq < r; jq++)
        for (iq = 0; iq < r; iq++) t[jq * r + iq] = (uint8_t)rr_cov_at(r, iq, jq);
    return t;
}
/* col over a pixel by a / 255 (a 1 .. 254): per channel, as put() */
static inline uint32_t rr_blend(uint32_t d, uint32_t col, int a)
{
    int sh, out = 0;
    for (sh = 16; sh >= 0; sh -= 8) out |= blend_ch((int)((d >> sh) & 255u), (int)((col >> sh) & 255u), a) << sh;
    return 0xFF000000u | (uint32_t)out;
}
static void rr_span(gpix_t *row, int i0, int i1, uint32_t col, int a)   /* pixels i0 .. i1 - 1 of a row */
{
    int i;
    if (a >= 255) { fill32(row + i0, i1 - i0, GPIX(col)); (void)i; }
    else {
        gpix_t last = 0, out = 0;   /* (a run of one colour under it blends once) */
        for (i = i0; i < i1; i++) {
            if (row[i] != last || i == i0) { last = row[i]; out = GPIX(rr_blend(GPIX_RGB(last), col, a)); }
            row[i] = out;
        }
    }
}
/* a rounded rectangle: the straight part of each row is one span (a fill, or one blend); only the corners' pixels take a coverage,
 * from a table made once a radius (integers: a float operation costs the FM-1 a library call). Rows and columns are clipped first. */
/* a rounded rectangle drawn next over this one, opaque (rr_under): this one need not be drawn where that one covers fully */
static struct { int on, x, y, w, h, r; const uint8_t *tab; } rr_skip;
static void rr_skip_span(int yy, int *a, int *b)   /* row yy (absolute): the columns [a, b) the shape over it covers fully */
{
    const int j = yy - rr_skip.y, r = rr_skip.r;
    int jq, iq0 = 0;
    *a = *b = 0;
    if (!rr_skip.on || j < 0 || j >= rr_skip.h) return;
    jq = j < r ? j : rr_skip.h - 1 - j;
    if (jq < r) {   /* a corner row: from the first fully covered pixel of the quadrant (the middle part is full) */
        iq0 = r;
        if (rr_skip.tab) { int iq; for (iq = 0; iq < r; iq++) if (rr_skip.tab[jq * r + iq] >= 16) { iq0 = iq; break; } }
    }
    *a = rr_skip.x + iq0;
    *b = rr_skip.x + rr_skip.w - iq0;
}
static void rr_hole(GCanvas *c, int x, int y, int w, int h, int r, uint32_t top, uint32_t bot, int alpha, int hole)
{
    int i, j, j0, j1, hr, gstep = h > 1 ? 65536 / (h - 1) : 0;   /* the gradient's step per row, 8.8 fixed: one divide a call, none a row */
    const uint8_t *tab;
    if (w <= 0 || h <= 0) return;
    if (r > w / 2) r = w / 2;
    if (r > h / 2) r = h / 2;
    if (r < 0) r = 0;
    if (alpha <= 0) return;
    if (alpha > 255) alpha = 255;
    if (!use_grad && top != bot) top = bot = lerp256(top, bot, 128);
    tab = r ? rr_table(r) : 0;
    hr = r > 1 ? r : 1;   /* a hole: rows hr .. h - hr - 1 keep only their first and last pixel (what lies inside, another draws) */
    j0 = y < 0 ? -y : 0;
    j1 = y + h > c->h ? c->h - y : h;
    for (j = j0; j < j1; j++) {
        const uint32_t col = top == bot ? top : lerp256(top, bot, (j * gstep) >> 8);
        gpix_t *row = c->px + (y + j) * c->w + x;   /* (indexed by i: x + i is the column) */
        const int jq = j < r ? j : h - 1 - j, corner = jq < r;
        int lo = x < 0 ? -x : 0, hi = x + w > c->w ? c->w - x : w, m0 = corner ? r : 0, m1 = corner ? w - r : w;
        if (lo >= hi) return;
        if (hole && j >= hr && j < h - hr) {
            if (lo == 0) rr_span(row, 0, 1, col, alpha);
            if (hi == w) rr_span(row, w - 1, w, col, alpha);
            continue;
        }
        {
            int s0 = 0, s1 = 0, a0 = m0 > lo ? m0 : lo, a1 = m1 < hi ? m1 : hi;
            if (rr_skip.on) { rr_skip_span(y + j, &s0, &s1); s0 -= x; s1 -= x; }   /* (relative to this one) */
            if (s1 > s0 && s1 > a0 && s0 < a1) {   /* the middle, around what the shape over it covers */
                if (s0 > a0) rr_span(row, a0, s0, col, alpha);
                if (s1 < a1) rr_span(row, s1, a1, col, alpha);
            } else rr_span(row, a0, a1, col, alpha);
            if (!corner) continue;
            for (i = lo; i < hi && i < r; i++) {   /* the left corner, then the right one */
                int cov = tab ? tab[jq * r + i] : rr_cov_at(r, i, jq), a = (alpha * cov + 8) >> 4;
                if (i >= s0 && i < s1) continue;
                if (a > 0) row[i] = a >= 255 ? GPIX(col) : GPIX(rr_blend(GPIX_RGB(row[i]), col, a));
            }
            for (i = w - r > lo ? w - r : lo; i < hi; i++) {
                int iq = w - 1 - i, cov = tab ? tab[jq * r + iq] : rr_cov_at(r, iq, jq), a = (alpha * cov + 8) >> 4;
                if (i >= s0 && i < s1) continue;
                if (a > 0) row[i] = a >= 255 ? GPIX(col) : GPIX(rr_blend(GPIX_RGB(row[i]), col, a));
            }
        }
    }
}
static void rr(GCanvas *c, int x, int y, int w, int h, int r, uint32_t top, uint32_t bot, int alpha) { rr_hole(c, x, y, w, h, r, top, bot, alpha, 0); }
/* a rounded rectangle in a 1 px border: the same pixels as the border's rectangle and then the inner one (1 in, r - 1), but the
 * border's inside, which the inner one covers, is not drawn first */
void g_rrect_frame(GCanvas *c, int x, int y, int w, int h, int r, uint32_t edge, uint32_t fill)
{ REC("frame", I_(x, y, w, h, r), I_(fill, edge), 0); 
    if (SC(c)) {   /* (the border a unit wide: the edge's shape whole, the inside over it) */
        GCanvas p = PHYS(c); const int k = c->s;
        rr(&p, x * k, y * k, w * k, h * k, r * k, edge, edge, 255);
        rr(&p, x * k + k, y * k + k, w * k - 2 * k, h * k - 2 * k, (r - 1) * k, fill, fill, 255);
        return;
    }
    rr_hole(c, x, y, w, h, r, edge, edge, 255, 1);
    rr(c, x + 1, y + 1, w - 2, h - 2, r - 1, fill, fill, 255);
}
/* a translucent rounded rectangle (a shadow) under one that is drawn next over it, opaque: the pixels that one covers fully are not
 * blended first (the same pixels as g_rrect_a, then the opaque one) */
void g_rrect_a_under(GCanvas *c, int x, int y, int w, int h, int r, uint32_t col, int alpha, int ux, int uy, int uw, int uh, int ur)
{ REC("rect", I_(x, y, w, h, r, alpha), I_(col), 0); 
    if (SC(c)) { GCanvas p = PHYS(c); const int k = c->s; g_rrect_a_under(&p, x * k, y * k, w * k, h * k, r * k, col, alpha, ux * k, uy * k, uw * k, uh * k, ur * k); return; }
    if (ur > uw / 2) ur = uw / 2;
    if (ur > uh / 2) ur = uh / 2;
    if (ur < 0) ur = 0;
    rr_skip.on = 1; rr_skip.x = ux; rr_skip.y = uy; rr_skip.w = uw; rr_skip.h = uh; rr_skip.r = ur;
    rr_skip.tab = ur ? rr_table(ur) : 0;
    rr_hole(c, x, y, w, h, r, col, col, alpha, 0);
    rr_skip.on = 0;
}
void g_rrect_grad_a(GCanvas *c, int x, int y, int w, int h, int r, uint32_t top, uint32_t bottom, int alpha)
{ REC("grad", I_(x, y, w, h, r, alpha), I_(top, bottom), 0); 
    if (SC(c)) { GCanvas p = PHYS(c); const int k = c->s; rr(&p, x * k, y * k, w * k, h * k, r * k, top, bottom, alpha); return; }
    rr(c, x, y, w, h, r, top, bottom, alpha);
}
void g_rrect_a(GCanvas *c, int x, int y, int w, int h, int r, uint32_t col, int alpha) { REC("rect", I_(x, y, w, h, r, alpha), I_(col), 0);  g_rrect_grad_a(c, x, y, w, h, r, col, col, alpha); }
void g_rrect_grad(GCanvas *c, int x, int y, int w, int h, int r, uint32_t top, uint32_t bottom) { REC("grad", I_(x, y, w, h, r, 255), I_(top, bottom), 0);  g_rrect_grad_a(c, x, y, w, h, r, top, bottom, 255); }
void g_rrect(GCanvas *c, int x, int y, int w, int h, int r, uint32_t col) { REC("rect", I_(x, y, w, h, r, 255), I_(col), 0);  g_rrect_a(c, x, y, w, h, r, col, 255); }
void g_shadow(GCanvas *c, int x, int y, int w, int h, int r, int dx, int dy, int blur, uint32_t col, int pct)
{ REC("shadow", I_(x, y, w, h, r, dx, dy, blur, pct), I_(col), 0); 
    if (SC(c)) { GCanvas p = PHYS(c); const int q = c->s; g_shadow(&p, x * q, y * q, w * q, h * q, r * q, dx * q, dy * q, blur * q, col, pct); return; }   /* (a smoother edge: more layers) */
    int k, a = pct * 255 / 100 / (blur + 1);
    for (k = blur; k >= 0; k--)   /* the widest layer first: the core is covered by every layer, the edge by one */
        g_rrect_a(c, x + dx - k, y + dy - k, w + 2 * k, h + 2 * k, r + k, col, a);
}

/* ------------------------------------------------- depth (Logic-like) --- */
/* All integer, no divide per pixel. Opaque gradients cost what a flat fill costs; only the 1 px lines and the shadow rows blend. */
static uint32_t shade(uint32_t col, int pct, uint32_t to) { return lerp256(col, to, pct * 256 / 100); }   /* (constant pct: folded) */
uint32_t g_mid(uint32_t a, uint32_t b) { return lerp256(a, b, 128); }
void g_vgrad(GCanvas *c, int x, int y, int w, int h, uint32_t top, uint32_t bot)
{ REC("grad", I_(x, y, w, h, 0, 255), I_(top, bot), 0); 
    int j, step = h > 1 ? 65536 / (h - 1) : 0;
    if (!use_grad) { g_fill(c, x, y, w, h, lerp256(top, bot, 128)); return; }
    for (j = 0; j < h; j++) g_fill(c, x, y + j, w, 1, lerp256(top, bot, (j * step) >> 8));
}
/* a flat fill of a rectangle but for a hole in it (what another part covers): the rows above and below, the sides beside */
void g_fill_around(GCanvas *c, int x, int y, int w, int h, int hx, int hy, int hw, int hh, uint32_t col)
{ REC("around", I_(x, y, w, h, hx, hy, hw, hh), I_(col), 0); 
    if (hw <= 0 || hh <= 0) { g_fill(c, x, y, w, h, col); return; }
    g_fill(c, x, y, w, hy - y, col);
    g_fill(c, x, hy + hh, w, y + h - (hy + hh), col);
    g_fill(c, x, hy, hx - x, hh, col);
    g_fill(c, hx + hw, hy, x + w - (hx + hw), hh, col);
}
void g_hline_a(GCanvas *c, int x, int y, int w, uint32_t col, int alpha)   /* (as put a pixel at a time; a run of one colour blends once) */
{ REC("rect", I_(x, y, w, 1, 0, alpha), I_(col), 0); 
    if (SC(c)) { GCanvas p = PHYS(c); int k; for (k = 0; k < c->s; k++) g_hline_a(&p, x * c->s, y * c->s + k, w * c->s, col, alpha); return; }   /* (a unit high) */
    int x0 = x < 0 ? 0 : x, x1 = x + w > c->w ? c->w : x + w;
    if ((unsigned)y >= (unsigned)c->h || alpha <= 0 || x0 >= x1) return;
    rr_span(c->px + y * c->w, x0, x1, col & 0xFFFFFFu, alpha > 255 ? 255 : alpha);
}
/* soft shadow under a part: `rows` lines below its bottom edge, fading, inset by `inset` px each side (cheap: rows x width blends) */
void g_drop(GCanvas *c, int x, int y, int w, int h, int inset, int rows, int pct)
{ REC("drop", I_(x, y, w, h, inset, rows, pct), I_(0), 0); 
    int k, a = pct * 255 / 100;
    for (k = 0; k < rows; k++) {
        g_hline_a(c, x + inset + k, y + h + k, w - 2 * (inset + k), 0x000000, a);
        a = a * 5 / 8;
    }
}
/* a bevel inside a rounded part: a light line along the top, a dark one along the bottom (the corners left alone) */
void g_bevel(GCanvas *c, int x, int y, int w, int h, int r, int hi, int lo)
{ REC("bevel", I_(x, y, w, h, r, hi, lo), I_(0), 0); 
    if (w - 2 * r < 2 || h < 4) return;
    if (hi) g_hline_a(c, x + r, y, w - 2 * r, 0xFFFFFF, hi);
    if (lo) g_hline_a(c, x + r, y + h - 1, w - 2 * r, 0x000000, lo);
}
/* a raised panel: a dark outline, a face lit from above (+6 % to -6 %), a light top edge, a dark bottom edge, a soft drop shadow */
void g_panel(GCanvas *c, int x, int y, int w, int h, int r, uint32_t face, int shadow)
{ REC("panel", I_(x, y, w, h, r, shadow), I_(face), 0); 
    if (shadow) g_drop(c, x, y, w, h, r > 2 ? r - 1 : 0, 3, shadow);
    g_rrect(c, x, y, w, h, r, shade(face, 55, 0x000000));
    g_rrect_grad(c, x + 1, y + 1, w - 2, h - 2, r - 1 < 0 ? 0 : r - 1, shade(face, 6, 0xFFFFFF), shade(face, 6, 0x000000));
    g_bevel(c, x + 1, y + 1, w - 2, h - 2, r, 36, 40);
}
/* a recess: darker than its ground, shaded along its top edge, a faint light line along its bottom edge */
void g_sunken(GCanvas *c, int x, int y, int w, int h, int r, uint32_t base)
{ REC("sunken", I_(x, y, w, h, r), I_(base), 0); 
    if (SC(c)) g_rrect(c, x, y, w, h, r, shade(base, 14, 0xFFFFFF));   /* (scaled: the shape whole, the next one over its inside) */
    else rr_hole(c, x, y, w, h, r, shade(base, 14, 0xFFFFFF), shade(base, 14, 0xFFFFFF), 255, 1);   /* (its inside is the next one's) */
    g_rrect_grad(c, x + 1, y + 1, w - 2, h - 2, r - 1 < 0 ? 0 : r - 1, shade(base, 45, 0x000000), shade(base, 18, 0x000000));
    g_hline_a(c, x + 1 + (r > 2 ? r - 1 : 0), y + 1, w - 2 - 2 * (r > 2 ? r - 1 : 0), 0x000000, 150);   /* the inner top edge */
    if (w - 2 * r > 2) g_hline_a(c, x + r, y + h - 1, w - 2 * r, 0xFFFFFF, 18);
}
