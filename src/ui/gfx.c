/* The knob, in integers on every device: the ring and the arc a pixel at a time (a float coverage over 40 segments was most of the
 * mixer's frame on the FM-1). atan2 in quarter degrees, 0..1439, y down (screen). */
static void curve16(GCanvas *c, const int *p16, int n, int th16, uint32_t col);   /* (below: the curve) */
static int iatan2q(int y, int x)
{
    int ax = x < 0 ? -x : x, ay = y < 0 ? -y : y, z, a;
    if (!ax && !ay) return 0;
    if (ay <= ax) { z = (ay << 10) / ax; a = (z * 180 + ((z * (1024 - z)) >> 10) * 63) >> 10; }
    else { z = (ax << 10) / ay; a = 360 - ((z * 180 + ((z * (1024 - z)) >> 10) * 63) >> 10); }
    if (x < 0) a = 720 - a;
    if (y < 0) a = 1440 - a;
    return a % 1440;
}
/* a ring's pixel at (dx16, dy16) from its centre (1/16 px): its coverage (0: none) and its angle from the start (135 degrees),
 * clockwise; r16 its radius, hw16 half its width (1/16 px; a pixel of soft edge across it) */
static int knob_cov(int dx16, int dy16, int r16, int hw16, int *u)
{
    const int d16 = (int)isqrt((uint32_t)(dx16 * dx16 + dy16 * dy16));
    int e = d16 - r16, cov;
    if (e < 0) e = -e;
    cov = e <= hw16 - 8 ? 255 : e >= hw16 + 8 ? 0 : (hw16 + 8 - e) * 16;   /* (2 px wide a unit: e <= 8 full, 24 none) */
    if (!cov) return 0;
    *u = iatan2q(dy16, dx16) - 540; if (*u < 0) *u += 1440;
    return *u > 1080 ? 0 : cov;   /* (the gap at the bottom) */
}
/* a ring's pixels for a radius, made once (two radii kept): its offset, its coverage and its angle from the start. A knob then
 * costs a blend a pixel, no root and no angle (they were most of a knob's time on the FM-1) */
typedef struct { int8_t dx, dy; uint8_t cov; uint8_t pad; int16_t u; } knob_px_t;
#define KNOB_PX 256   /* a ring up to radius 14 (252 pixels); a larger one is drawn as it is computed */
#define KNOB_R 14
static knob_px_t knob_px[2][KNOB_PX];
static int knob_n[2], knob_r[2] = {-1, -1}, knob_next;
static const knob_px_t *knob_ring(int r, int *n)
{
    int s, x, y, k = 0;
    for (s = 0; s < 2; s++) if (knob_r[s] == r) { *n = knob_n[s]; return knob_px[s]; }
    if (r > KNOB_R) return 0;
    s = knob_next; knob_next ^= 1;
    for (y = -r - 2; y <= r + 2; y++)
        for (x = -r - 2; x <= r + 2; x++) {
            int d2 = x * x + y * y, cov, u;
            if (d2 > (r + 2) * (r + 2) || d2 < (r - 2) * (r - 2)) continue;
            cov = knob_cov(x * 16, y * 16, r * 16, 16, &u);
            if (!cov || k >= KNOB_PX) continue;   /* (k: never past, by KNOB_R) */
            knob_px[s][k].dx = (int8_t)x; knob_px[s][k].dy = (int8_t)y; knob_px[s][k].cov = (uint8_t)cov; knob_px[s][k].u = (int16_t)u; k++;
        }
    knob_r[s] = r; knob_n[s] = k;
    *n = k;
    return knob_px[s];
}
void g_knob(GCanvas *c, int cx, int cy, int r, int v, int bipolar, uint32_t arc, uint32_t ring, uint32_t mark)
{ REC("knob", I_(cx, cy, r, v, bipolar), I_(arc, ring, mark), 0);
    const int k1 = SC(c) ? c->s : 1;   /* (a scaled canvas: its pixels a unit; the ring, its width and the mark at that density) */
    GCanvas p = SC(c) ? PHYS(c) : *c;
    int lo, hi, from = bipolar ? 540 : 0, fv, n, k;
    const knob_px_t *px;
    if (v < 0) v = 0; else if (v > 100) v = 100;
    fv = v * 1080 / 100;   /* the value along the 270 degrees, quarter degrees */
    lo = from < fv ? from : fv; hi = from < fv ? fv : from;
    px = k1 == 1 ? knob_ring(r, &n) : 0;
    if (px)
        for (k = 0; k < n; k++) {
            const int u = px[k].u;
            put(&p, cx + px[k].dx, cy + px[k].dy, (hi - lo > 1 && u >= lo && u <= hi) ? arc : ring, px[k].cov, 255);
        }
    else {   /* a large ring, a pixel at a time: its centre the unit pixel's middle, (cx + 1/2) k1 */
        const int c16x = (cx * 16 + 8) * k1, c16y = (cy * 16 + 8) * k1, rr = (r + 2) * k1;
        int x, y;
        for (y = cy * k1 - rr; y <= cy * k1 + k1 + rr; y++)
            for (x = cx * k1 - rr; x <= cx * k1 + k1 + rr; x++) {
                int cov, u;
                cov = knob_cov(x * 16 + 8 - c16x, y * 16 + 8 - c16y, r * k1 * 16, 16 * k1, &u);
                if (cov) put(&p, x, y, (hi - lo > 1 && u >= lo && u <= hi) ? arc : ring, cov, 255);
            }
    }
    if (ui_mark) ui_mark(26);
    if (bipolar) g_fill(c, cx, cy - r - 1, 1, 3, ring);
    {   /* the mark: a short line at the value's angle, from a table of the 101 angles (made once), in 1/16 px */
        static int16_t kc[101], ks[101];
        static int made;
        int p16[4];
        if (!made) {
            int q;
            for (q = 0; q <= 100; q++) {
                const uint32_t ph = (uint32_t)(13500 + 270 * q) * 119305u;   /* 135 + 2.7 q degrees (2^32 a turn: 2^32 / 36000 a hundredth) */
                kc[q] = (int16_t)g_isin(ph + 0x40000000u); ks[q] = (int16_t)g_isin(ph);
            }
            made = 1;
        }
        p16[0] = (cx * 16 + 8) * k1 + ((kc[v] * (r - 5) * k1) >> 10); p16[1] = (cy * 16 + 8) * k1 + ((ks[v] * (r - 5) * k1) >> 10);
        p16[2] = (cx * 16 + 8) * k1 + ((kc[v] * (r - 1) * k1) >> 10); p16[3] = (cy * 16 + 8) * k1 + ((ks[v] * (r - 1) * k1) >> 10);
        curve16(&p, p16, 2, 16 * k1 + 8, mark);   /* (2 px thick a unit) */
    }
}

/* ------------------------------------------------------------ curves --- */
/* The curves, in integers on every device: points in 1/16 px; a segment's t from one division per segment; the coverage from the
 * squared distance through a table made for this width; coverage kept in bytes. */
#ifdef KREISEL_CURVE_W
/* A device that counts its RAM (the FM-1: KREISEL_CURVE_W / _H, 1 byte a pixel): the largest curve box (a curve whose box is bigger
 * is not drawn), the widest curve */
#ifndef KREISEL_CURVE_H
#define KREISEL_CURVE_H 240
#endif
enum { CV_W = KREISEL_CURVE_W, CV_H = KREISEL_CURVE_H, CV_TH16 = 56 };
static uint8_t covbuf[CV_W * CV_H];   /* zero between calls: a call clears what it touched (its rows' spans), not the whole box */
static int16_t cov_lo[CV_H], cov_hi[CV_H];   /* each row's touched span, this call */
static int cov_room(int bw, int bh) { return bw <= CV_W && bh <= CV_H; }
#else
/* elsewhere: the buffers as large as the largest box so far (a scaled canvas's are large), the curves up to 30 px wide */
enum { CV_TH16 = 248 };
static uint8_t *covbuf;
static int16_t *cov_lo, *cov_hi;
static size_t cov_n;
static int cov_h;
static int cov_room(int bw, int bh)
{
    if (bw > 8192 || bh > 8192) return 0;
    if ((size_t)bw * (size_t)bh > cov_n) {   /* (zeroed: the buffer is zero between calls) */
        uint8_t *nb = calloc((size_t)bw * (size_t)bh, 1);
        if (!nb) return 0;
        free(covbuf); covbuf = nb; cov_n = (size_t)bw * (size_t)bh;
    }
    if (bh > cov_h) {
        int16_t *lo = malloc(sizeof *lo * (size_t)bh), *hi = malloc(sizeof *hi * (size_t)bh);
        if (!lo || !hi) { free(lo); free(hi); return 0; }
        free(cov_lo); free(cov_hi); cov_lo = lo; cov_hi = hi; cov_h = bh;
    }
    return 1;
}
#endif
#define CV_LUT ((CV_TH16 + 8) * (CV_TH16 + 8) + 1)
static uint8_t cov_luts[2][CV_LUT];   /* a table for each of the last two widths (a curve 1.2 px, a knob's mark 2) */
static int cov_lut_th[2] = {-1, -1}, cov_lut_next;
#define SEG16 512   /* a segment longer than this (32 px) either way is drawn in pieces: its t stays exact to a fraction of a pixel */
/* the curve from points in 1/16 px; th16 = thick / 2 + 1/2 */
static void curve16(GCanvas *c, const int *p16, int n, int th16, uint32_t col)
{
    const uint8_t *cov_lut;
    int r16, lutn, i, x, y, bx, by, bw, bh, minx = 1 << 30, miny = 1 << 30, maxx = -(1 << 30), maxy = -(1 << 30);
    if (n < 2) return;
    if (th16 > CV_TH16) th16 = CV_TH16;
    r16 = th16 + 8;                          /* the reach: the coverage is 0 past it */
    lutn = r16 * r16;
    {   /* the table for this width: one of the two kept, else made (it was made every call: most of a knob) */
        int k = cov_lut_th[0] == th16 ? 0 : cov_lut_th[1] == th16 ? 1 : -1;
        if (k < 0) {
            k = cov_lut_next; cov_lut_next ^= 1;
            for (i = 0; i <= lutn; i++) {
                int cv = th16 - (int)isqrt((uint32_t)i);
                cov_luts[k][i] = (uint8_t)(cv <= 0 ? 0 : cv >= 16 ? 255 : cv * 16);
            }
            cov_lut_th[k] = th16;
        }
        cov_lut = cov_luts[k];
    }
    for (i = 0; i < n; i++) {
        const int px = p16[2 * i], py = p16[2 * i + 1];
        if (px < minx) minx = px;
        if (px > maxx) maxx = px;
        if (py < miny) miny = py;
        if (py > maxy) maxy = py;
    }
    bx = (minx - r16) >> 4; by = (miny - r16) >> 4;
    bw = ((maxx + r16) >> 4) - bx + 2; bh = ((maxy + r16) >> 4) - by + 2;
    if (bw < 1 || bh < 1 || !cov_room(bw, bh)) return;
    for (y = 0; y < bh; y++) { cov_lo[y] = (int16_t)bw; cov_hi[y] = -1; }
    for (i = 0; i + 1 < n; i++) {
        const int X0 = p16[2 * i], Y0 = p16[2 * i + 1], X1 = p16[2 * i + 2], Y1 = p16[2 * i + 3];
        const int am = abs(X1 - X0) > abs(Y1 - Y0) ? abs(X1 - X0) : abs(Y1 - Y0), np = am > SEG16 ? (am + SEG16 - 1) / SEG16 : 1;
        int j;
        for (j = 0; j < np; j++) {
        const int x0 = np == 1 ? X0 : X0 + (X1 - X0) * j / np, y0 = np == 1 ? Y0 : Y0 + (Y1 - Y0) * j / np;
        const int x1 = np == 1 ? X1 : X0 + (X1 - X0) * (j + 1) / np, y1 = np == 1 ? Y1 : Y0 + (Y1 - Y0) * (j + 1) / np;
        int dx = x1 - x0, dy = y1 - y0, len2 = dx * dx + dy * dy, inv = len2 > 0 ? (int)((1u << 30) / (uint32_t)len2) : 0, ext;
        int sx0 = ((x0 < x1 ? x0 : x1) - r16) >> 4, sx1 = ((x0 < x1 ? x1 : x0) + r16) >> 4;
        int sy0 = ((y0 < y1 ? y0 : y1) - r16) >> 4, sy1 = ((y0 < y1 ? y1 : y0) + r16) >> 4;
        if (sx0 < bx) sx0 = bx;
        if (sy0 < by) sy0 = by;
        if (sx1 >= bx + bw) sx1 = bx + bw - 1;
        if (sy1 >= by + bh) sy1 = by + bh - 1;
        {   /* the reach along a row (r / sin, and a margin), once a segment; 0: scan the whole box (a flat one) */
            const int adx = dx < 0 ? -dx : dx, ady = dy < 0 ? -dy : dy;
            ext = ady && adx < ady * 8 ? r16 + r16 * adx / ady + 32 : 0;
        }
        for (y = sy0; y <= sy1; y++) {
            uint8_t *row = covbuf + (y - by) * bw - bx;
            int xa = sx0, xb = sx1;
            if (ext) {   /* only the columns near the segment on this row: its x here (clamped to its ends), the reach either way
                          * over the line's slope (a pixel further has no coverage): the box of a slanted segment is mostly empty */
                int t2 = (y * 16 + 8 - y0) * 4096 / dy, xm;
                t2 = t2 < 0 ? 0 : t2 > 4096 ? 4096 : t2;
                xm = x0 + ((t2 * dx) >> 12);
                if (((xm - ext) >> 4) > xa) xa = (xm - ext) >> 4;
                if (((xm + ext) >> 4) < xb) xb = (xm + ext) >> 4;
            }
            if (xa <= xb) {   /* (the row's span: the composite and the clearing go no wider) */
                if (xa - bx < cov_lo[y - by]) cov_lo[y - by] = (int16_t)(xa - bx);
                if (xb - bx > cov_hi[y - by]) cov_hi[y - by] = (int16_t)(xb - bx);
            }
            for (x = xa; x <= xb; x++) {
                int px = x * 16 + 8 - x0, py = y * 16 + 8 - y0, t, ex, ey, d2;
                if (len2) {
                    int dot = px * dx + py * dy;
                    t = dot <= 0 ? 0 : dot >= len2 ? 4096 : (int)(((int64_t)dot * inv) >> 18);   /* 0..4096 */
                    ex = px - ((t * dx) >> 12); ey = py - ((t * dy) >> 12);
                } else { ex = px; ey = py; }
                d2 = ex * ex + ey * ey;
                if (d2 < lutn && cov_lut[d2] > row[x]) row[x] = cov_lut[d2];
            }
        }
        }
    }
    for (y = 0; y < bh; y++) {   /* the touched spans: composite, then clear */
        uint8_t *row = covbuf + y * bw;
        for (x = cov_lo[y]; x <= cov_hi[y]; x++)
            if (row[x]) { put(c, bx + x, by + y, col, row[x], 255); row[x] = 0; }
    }
}
#define CURVE_PTS 256
void g_curve16(GCanvas *c, const int *p16, int n, int th16, uint32_t col)
{ REC_CURVE16(p16, n, th16, col, -1);
    if (SC(c)) {   /* the points and the width at the canvas's density */
        GCanvas p = PHYS(c);
        int q[2 * CURVE_PTS], i;
        if (n > CURVE_PTS) n = CURVE_PTS;
        for (i = 0; i < 2 * n; i++) q[i] = p16[i] * c->s;
        curve16(&p, q, n, (th16 - 8) * c->s + 8, col);
        return;
    }
    curve16(c, p16, n, th16, col);
}
/* a quarter of the sine, Q14, 64 steps to the quarter turn: (int16_t)(sinf(i * 2 pi / 256) * 16384), which is symmetric (a table, not
 * made at start: on the FM-1 that was 257 float sines and 514 bytes of RAM) */
static const int16_t SINQ[65] = {
    0, 402, 803, 1205, 1605, 2005, 2404, 2801, 3196, 3589, 3980, 4369, 4756, 5139, 5519, 5896,
    6269, 6639, 7005, 7366, 7723, 8075, 8423, 8765, 9102, 9434, 9759, 10079, 10393, 10701, 11002, 11297,
    11585, 11866, 12139, 12406, 12665, 12916, 13159, 13395, 13622, 13842, 14053, 14255, 14449, 14634, 14810, 14978,
    15136, 15286, 15426, 15557, 15678, 15790, 15892, 15985, 16069, 16142, 16206, 16260, 16305, 16339, 16364, 16379, 16384};
static int sin256(uint32_t i)   /* the table at i of 256 steps a turn (0..256) */
{
    return i <= 64u ? SINQ[i] : i <= 128u ? SINQ[128u - i] : i <= 192u ? -SINQ[i - 128u] : -SINQ[256u - i];
}
int g_isin(uint32_t ph)   /* sin of a phase (a turn = 2^32), Q14 */
{
    const uint32_t i = ph >> 24, f = (ph >> 16) & 255u;
    const int a = sin256(i), b = sin256(i + 1u);
    return a + (((b - a) * (int)f) >> 8);
}
/* 2^(x24 / 2^24) * 2^q, rounded (the caller keeps it under 2^32): the fraction's power from its series to the 9th term, in Q30 (within
 * about 1e-8), the whole part a shift */
uint32_t g_exp2(int32_t x24, int q)
{
    static const uint32_t C[10] = {1073741824u, 744261118u, 257941248u, 59597083u, 10327387u, 1431680u, 165394u, 16377u, 1419u, 109u};
    const int32_t i = x24 >> 24;   /* (floor) */
    const uint32_t f = (uint32_t)(x24 & 0xFFFFFF) << 6;   /* the fraction, Q30 */
    uint32_t p = C[9];
    int k, sh;
    for (k = 8; k >= 0; k--) p = C[k] + k_umulsh(p, f, 30);
    sh = (int)i + q - 30;
    if (sh >= 0) return p << sh;   /* (the caller's range: no overflow) */
    if (sh < -31) return 0;
    return (uint32_t)(((uint64_t)p + ((uint64_t)1 << (-sh - 1))) >> -sh);
}
/* log2(x16 / 2^16) in Q24, x16 > 0 (0: a large negative): the whole part from the top bit, the fraction a bit at a time by squaring */
int32_t g_log2(uint32_t x16)
{
    int n = 31, i;
    int32_t r;
    uint32_t m;
    if (!x16) return -(32 << 24);
    while (!(x16 >> n)) n--;
    m = n >= 30 ? x16 >> (n - 30) : x16 << (30 - n);   /* the mantissa, Q30: 1 .. 2 */
    r = (n - 16) * (1 << 24);
    for (i = 23; i >= 0; i--) {
        m = k_umulsh(m, m, 30);
        if (m >= 1u << 31) { m >>= 1; r += 1 << i; }
    }
    return r;
}
uint32_t g_isqrt(uint32_t v) { return isqrt(v); }
/* the area under a curve of points in 1/16 px (as g_curve16's), down to y = base: a column a pixel */
void g_curve_fill16(GCanvas *c, const int *p16, int n, int base, uint32_t col)
{ REC_CURVE16(p16, n, 0, col, base);
    int i, x;
    if (SC(c)) {   /* a column a pixel of the canvas, not a unit */
        GCanvas p = PHYS(c);
        int q[2 * CURVE_PTS];
        if (n > CURVE_PTS) n = CURVE_PTS;
        for (i = 0; i < 2 * n; i++) q[i] = p16[i] * c->s;
        g_curve_fill16(&p, q, n, base * c->s, col);
        return;
    }
    for (i = 0; i + 1 < n; i++) {
        const int x0 = p16[2 * i], y0 = p16[2 * i + 1], x1 = p16[2 * i + 2], y1 = p16[2 * i + 3], xs = (x0 + 15) >> 4;   /* ceil */
        for (x = xs; x * 16 < x1 || (x == xs && x0 == x1); x++) {
            int t = x1 > x0 ? ((x * 16 + 8 - x0) * 4096) / (x1 - x0) : 0, y;   /* 0..4096 */
            t = t < 0 ? 0 : t > 4096 ? 4096 : t;
            y = (y0 + (((y1 - y0) * t) >> 12)) >> 4;
            if (y < base) g_fill(c, x, y, 1, base - y, col);
            if (x1 <= x0) break;
        }
    }
}

/* ------------------------------------------------------- pixel font --- */
extern const char K_PIX5_CHARS[];
extern const uint8_t K_PIX5[][7];
int g_pix5_w(const char *s, int scale) { int n = 0; while (s && s[n]) n++; return n ? (n * 6 - 1) * scale : 0; }
int g_pix5(GCanvas *c, int x, int y, const char *s, uint32_t col, int scale)
{ REC("pix", I_(x, y, scale, 5), I_(col), s); 
    for (; s && *s; s++, x += 6 * scale) {
        char ch = *s >= 'a' && *s <= 'z' ? (char)(*s - 32) : *s;
        const char *at = strchr(K_PIX5_CHARS, ch);
        int r, b;
        if (!at || ch == 0) continue;
        for (r = 0; r < 7; r++)
            for (b = 0; b < 5; b++)
                if ((K_PIX5[at - K_PIX5_CHARS][r] >> (4 - b)) & 1) g_fill(c, x + b * scale, y + r * scale, scale, scale, col);
    }
    return x;
}
extern const uint8_t K_PIX8[95][8];
int g_pix8_w(const char *s, int scale) { int n = 0; while (s && s[n]) n++; return n ? (n * 8 - 1) * scale : 0; }
int g_pix8(GCanvas *c, int x, int y, const char *s, uint32_t col, int scale)
{ REC("pix", I_(x, y, scale, 8), I_(col), s); 
    for (; s && *s; s++, x += 8 * scale) {
        int ch = *s >= 'a' && *s <= 'z' ? *s - 32 : (unsigned char)*s, r, b;
        if (ch < 33 || ch > 126) continue;
        for (r = 0; r < 8; r++) {
            const uint8_t row = K_PIX8[ch - 32][r];
            for (b = 0; b < 8; b++)
                if ((row >> (7 - b)) & 1u) {   /* a run of pixels as one fill */
                    int e = b;
                    while (e + 1 < 8 && ((row >> (6 - e)) & 1u)) e++;
                    g_fill(c, x + b * scale, y + r * scale, (e - b + 1) * scale, scale, col);
                    b = e;
                }
        }
    }
    return x;
}
