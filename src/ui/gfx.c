/* ------------------------------------------------------------- icons --- */
static void dot_line(GCanvas *c, int x0, int y0, int x1, int y1, int t, uint32_t col)   /* t px thick */
{
    int dx = abs(x1 - x0), dy = -abs(y1 - y0), sx = x0 < x1 ? 1 : -1, sy = y0 < y1 ? 1 : -1, err = dx + dy;
    for (;;) {
        int e2 = 2 * err;   /* (both tests on the same value: after the first step's update they could walk off, and never end) */
        g_fill(c, x0, y0, t, t, col);
        if (x0 == x1 && y0 == y1) break;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}
/* ---- the icon cache ---- the vector icons are rasterised from their outlines (a few thousand integer operations each), so each (icon, size, layer) is
 * rasterised once into 8-bit coverage and drawn from that afterwards: a blit of integers. A pool of a few KB; when it is full an icon
 * is drawn the long way, as before. */
#ifndef KREISEL_ICON_POOL
#ifdef KREISEL_BITMAP_FONT
#define KREISEL_ICON_POOL 12288
#else
#define KREISEL_ICON_POOL (1 << 20)   /* (a desktop: icons at a scaled canvas's density too) */
#endif
#endif
#ifdef KREISEL_BITMAP_FONT   /* (the FM-1: its icons small, the table as it was: its RAM is counted) */
typedef struct { int16_t id; uint8_t size, layer, w, h; int8_t bx, by; uint16_t off; } icon_ent;
#define ICON_TAB 96
#define ICON_MAX 128
#else
typedef struct { int16_t id; uint16_t size; uint8_t layer; uint16_t w, h; int16_t bx, by; uint32_t off; } icon_ent;
#define ICON_TAB 256
#define ICON_MAX 1024
#endif
static uint8_t icon_pool[KREISEL_ICON_POOL];
static icon_ent icon_tab[ICON_TAB];
static int icon_n, icon_used;
static void icon_layer(GCanvas *c, int x, int y, int size, GIcon id, int layer, uint32_t col)
{
    const vface_t *f = layer ? &VI_FG : &VI_BG;
    const vglyph_t *g = layer ? &VI_FG_G[id] : &VI_BG_G[id];
    int i, ip, bx, by, w, h, xx, yy;
    icon_ent *e = 0;
    if (!g->nop) return;
    for (i = 0; i < icon_n; i++)
        if (icon_tab[i].id == (int16_t)id && icon_tab[i].size == size && icon_tab[i].layer == (uint8_t)layer) { e = &icon_tab[i]; break; }
    if (!e) {
        if (!vprep_i((int32_t)x * 65536, f, g, size, 2000, &ip, &bx, &by, &w, &h)) return;   /* (the baked outlines: 2000 units to the em) */
        if (icon_n < (int)(sizeof icon_tab / sizeof icon_tab[0]) && icon_used + w * h <= KREISEL_ICON_POOL && w < ICON_MAX && h < ICON_MAX && bx > -ICON_MAX && by > -ICON_MAX && bx < ICON_MAX && by < ICON_MAX) {
            uint8_t *o = icon_pool + icon_used;
            for (yy = 0; yy < h; yy++) {
                int32_t run = 0, *row = acc + yy * (w + 3);
                for (xx = 0; xx < w; xx++) { run += row[xx]; o[yy * w + xx] = (uint8_t)cov8(run); }
            }
            e = &icon_tab[icon_n++];
            e->id = (int16_t)id; e->size = size; e->layer = (uint8_t)layer; e->w = w; e->h = h;
            e->bx = bx; e->by = by; e->off = icon_used;
            icon_used += w * h;
        } else {   /* no room: the long way */
            for (yy = 0; yy < h; yy++) {
                int32_t run = 0, *row = acc + yy * (w + 3);
                for (xx = 0; xx < w; xx++) { int a; run += row[xx]; a = cov8(run); if (a) put(c, ip + bx + xx, y + size + by + yy, col, a, 255); }
            }
            return;
        }
    }
    {
        const uint8_t *o = icon_pool + e->off;
        for (yy = 0; yy < e->h; yy++)
            for (xx = 0; xx < e->w; xx++)
                if (o[yy * e->w + xx]) put(c, x + e->bx + xx, y + size + e->by + yy, col, o[yy * e->w + xx], 255);
    }
}
